const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const source = fs.readFileSync('web/app.js', 'utf8');
const context = vm.createContext({});
vm.runInContext(source.slice(source.indexOf('function libraryEntries('), source.indexOf('async function reload()')), context);
const file = (id, tags, autoTags = []) => ({id, title:id, filename:id+'.png', type:'image', tags, autoTags, categories:[], size:10, created:'2026-10-09', note:'원본 메모 '+id, source:'', trashed:0});
const library = {items:[file('b',['auto'], ['auto']), file('c',[]), file('a',['manual','auto'])], bundles:[{id:'bundle', title:'한 자료', note:'공통 설명', source:'', ids:['a','b']}]};
const entries = JSON.parse(JSON.stringify(context.libraryEntries(library)));
assert.equal(entries.length, 2);
assert.equal(entries[0].id, 'bundle');
assert.equal(entries[0].coverId, 'a');
assert.deepEqual(entries[0].memberIds, ['a','b']);
assert.equal(entries[0].size, 20);
assert.deepEqual(entries[0].autoTags, []);
assert.match(entries[0].searchText, /b.png/);
assert.match(entries[0].searchText, /원본 메모 a/);
assert.equal(entries[0].note, '공통 설명');
library.bundles[0].cover = 'b';
library.bundles[0].ids = ['b', 'a'];
assert.equal(context.libraryEntries(library)[0].coverId, 'b');
library.bundles[0].ids = ['a', 'b'];
assert.equal(context.libraryEntries(library)[0].coverId, 'b');
library.bundles = [];
assert.equal(context.libraryEntries(library).length, 3);
console.log('Bundle card, member search, metadata and split checks passed.');
