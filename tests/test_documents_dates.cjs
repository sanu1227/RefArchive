const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const source = fs.readFileSync('web/app.js', 'utf8');
const context = vm.createContext({});
vm.runInContext(source.slice(source.indexOf('function libraryEntries('), source.indexOf('async function reload()')), context);
vm.runInContext(source.slice(source.indexOf('function matchesMaterialDate('), source.indexOf('function filteredItems(')), context);
const file = (id, material_date) => ({id, type:'document', title:id, filename:id+'.txt', material_date, tags:[], categories:[], autoTags:[], size:3, created:'2026-10-18T00:00:00Z'});
const old = file('old', '1999-01-01'), newer = file('new', '2024-02-29'), missing = file('unknown', ''), leap = file('leap', '2000-02-29');
assert(context.matchesMaterialDate(missing, '', ''));
assert(!context.matchesMaterialDate(missing, '1900-01-01', ''));
assert(!context.matchesMaterialDate(old, '2024-01-01', '2000-01-01'));
assert(context.matchesMaterialDate(newer, '2024-02-29', '2024-02-29'));
assert(!context.matchesMaterialDate(old, '2000-01-01', '2025-01-01'));
assert.deepEqual([missing, old, newer, leap].sort((a,b) => context.compareMaterialDate(a,b)).map(x=>x.id), ['new','leap','old','unknown']);
assert.deepEqual([missing, old, newer, leap].sort((a,b) => context.compareMaterialDate(a,b,false)).map(x=>x.id), ['old','leap','new','unknown']);
const groups = (items, mode, ascending) => JSON.parse(JSON.stringify(context.materialDateGroups(items, mode, ascending)));
assert.deepEqual(groups([missing, old, newer, leap], 'year').map(x=>x[0]), ['2024','2000','1999','']);
assert.deepEqual(groups([missing, old, newer, leap], 'month', true).map(x=>x[0]), ['1999-01','2000-02','2024-02','']);
assert.equal(groups([missing, old], 'none').length, 1);
const localMidnight = new Date(2024, 0, 1, 0, 10);
const localItem = {...missing, created: localMidnight.toISOString()};
assert.deepEqual(groups([localItem], 'registered-day').map(x=>x[0]), ['2024-01-01'], 'Registration groups use local dates, not UTC slicing');
assert.deepEqual(groups([localItem], 'registered-month').map(x=>x[0]), ['2024-01']);
assert.deepEqual(groups([localItem], 'registered-year').map(x=>x[0]), ['2024']);
assert.deepEqual(groups([{...missing, created: 'invalid'}], 'registered-day').map(x=>x[0]), ['']);
const library = {items:[old, newer], bundles:[{id:'bundle', ids:['old','new'], title:'묶음'}]};
assert.equal(context.libraryEntries(library)[0].material_date, '', 'Bundle must never inherit the first file date implicitly');
library.bundles[0].material_date = '2023-01-01';
assert.equal(context.libraryEntries(library)[0].material_date, '2023-01-01');
console.log('Date bounds, undated order, year/month grouping and explicit bundle date checks passed.');
